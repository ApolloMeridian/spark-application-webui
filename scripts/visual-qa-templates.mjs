import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright-core';
import { parse } from 'yaml';

const baseUrl = process.env.QA_URL || 'http://127.0.0.1:5173';
const output = process.env.QA_OUTPUT || '.qa';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.QA_BROWSER || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe', headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  page.on('pageerror', (error) => errors.push(error.message));
  page.on('console', (event) => { if (event.type() === 'error') errors.push(event.text()); });
  await page.addInitScript(() => {
    localStorage.setItem('spark-console-locale', 'en-US');
    localStorage.setItem('spark-console-session', JSON.stringify({ id: 'mock-qa', username: 'demo-admin', displayName: 'demo-admin', role: 'admin', namespaces: [], authSource: 'mock', disabled: false, email: '', createdAt: '2026-10-08T00:00:00Z', updatedAt: '2026-10-08T00:00:00Z' }));
  });
  await page.goto(`${baseUrl}/applications/spark-prod/parquet-to-iceberg`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Save Template' }).waitFor();
  const original = await page.evaluate(() => JSON.parse(localStorage.getItem('spark-console-mock-applications')).find((x) => x.name === 'parquet-to-iceberg').yaml);
  const object = parse(original);
  object.metadata.annotations = { 'kubectl.kubernetes.io/last-applied-configuration': 'old applied config', 'custom/config': 'preserved' };
  object.metadata.managedFields = [{ 'f:executorState': { 'f:old-executor': {} } }];
  object.status = { driverInfo: { podName: 'old-driver' }, executorState: { 'old-executor': 'RUNNING' }, submissionID: 'old-submission' };
  await page.evaluate((manifest) => {
    const apps = JSON.parse(localStorage.getItem('spark-console-mock-applications'));
    apps.find((x) => x.name === 'parquet-to-iceberg').yaml = manifest;
    localStorage.setItem('spark-console-mock-applications', JSON.stringify(apps));
  }, JSON.stringify(object));
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Save Template' }).click();
  await page.waitForURL('**/templates');
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  const manifestEditor = dialog.locator('textarea.yaml-editor');
  const cleaned = await manifestEditor.inputValue();
  assert(!/managedFields|executorState|last-applied|submissionID|status:/.test(cleaned));
  assert(cleaned.includes('custom/config: preserved'));
  const templateName = 'Batch example';
  await dialog.getByRole('textbox').first().fill(templateName);
  const manifest = 'apiVersion: sparkoperator.k8s.io/v1beta2\nkind: SparkApplication\nmetadata:\n  name: parameter-demo\n  namespace: spark-prod\nspec:\n  image: spark:3.5.3\n  executor:\n    instances: "{{executorCount}}"\n';
  await manifestEditor.fill(manifest);
  await dialog.getByRole('button', { name: 'Add parameter' }).click();
  await dialog.getByPlaceholder('executorCount').fill('executorCount');
  const parameterCard = dialog.locator('.ant-card').last();
  await parameterCard.locator('.ant-select').first().click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^integer$/ }).click();
  await parameterCard.locator('.ant-form-item').filter({ has: page.locator('label', { hasText: 'Default value' }) }).getByRole('textbox').fill('3');
  await dialog.getByText('Parameter definitions', { exact: true }).click();
  await page.locator('.ant-select-dropdown:visible').waitFor({ state: 'hidden' });
  await page.screenshot({ path: `${output}/template-editor-1440.png`, fullPage: true });
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('spark-console-mock-templates')).find((x) => x.name === 'Batch example'));
  assert.equal(saved.parameters[0].type, 'integer');
  assert.equal(saved.parameters[0].default, '3');
  const row = page.getByRole('row').filter({ hasText: templateName });
  await row.getByRole('button', { name: /Use$/ }).click();
  await page.getByRole('button', { name: 'Render and validate' }).click();
  await page.waitForURL('**/submit');
  assert.equal(parse(await page.locator('.submit-card textarea.yaml-editor').inputValue()).spec.executor.instances, 3);

  await page.goto(`${baseUrl}/applications/spark-prod/parquet-to-iceberg`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'Clone application' }).click();
  await page.waitForURL('**/submit');
  const clone = await page.locator('.submit-card textarea.yaml-editor').inputValue();
  assert(!/managedFields|executorState|last-applied|submissionID|status:/.test(clone));
  assert.equal(parse(clone).metadata.name, 'parquet-to-iceberg-copy');

  await page.goto(`${baseUrl}/alerts`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: 'New rule' }).click();
  await dialog.getByRole('textbox').first().fill('Volume and image failures');
  await dialog.locator('.ant-select').first().click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^Diagnostic fingerprint$/ }).click();
  await dialog.locator('.ant-select').nth(1).click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^VOLUME_MOUNT$/ }).click();
  await page.locator('.ant-select-dropdown:visible .ant-select-item-option-content').filter({ hasText: /^IMAGE_PULL$/ }).click();
  await dialog.getByRole('textbox').first().click();
  await page.locator('.ant-select-dropdown:visible').waitFor({ state: 'hidden' });
  await page.screenshot({ path: `${output}/diagnostic-rule-1440.png`, fullPage: true });
  await page.setViewportSize({ width: 1024, height: 768 });
  await page.screenshot({ path: `${output}/diagnostic-rule-1024.png`, fullPage: true });
  const widths = await page.evaluate(() => ({ viewport: document.documentElement.clientWidth, document: document.documentElement.scrollWidth }));
  assert(widths.document <= widths.viewport);
  await dialog.getByRole('button', { name: 'OK', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const rule = await page.evaluate(() => JSON.parse(localStorage.getItem('spark-console-mock-alert-rules')).find((x) => x.name === 'Volume and image failures'));
  assert.deepEqual(rule.diagnosticCodes, ['VOLUME_MOUNT', 'IMAGE_PULL']);
  await page.getByRole('tab', { name: 'Rules', exact: true }).click();
  await page.getByRole('row').filter({ hasText: 'Volume and image failures' }).getByRole('button', { name: 'Edit' }).click();
  await dialog.waitFor();
  assert(await dialog.getByText('VOLUME_MOUNT', { exact: true }).isVisible());
  await dialog.getByRole('button', { name: 'Cancel' }).click();
  await page.goto(`${baseUrl}/templates`, { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: `Edit ${templateName}` }).click();
  await dialog.waitFor();
  assert.equal(await dialog.getByPlaceholder('executorCount').inputValue(), 'executorCount');
  await page.screenshot({ path: `${output}/template-editor-1024.png`, fullPage: true });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ result: 'passed', errors, widths, checks: ['clean template', 'parameter form persistence', 'typed render', 'clean clone', 'diagnostic code persistence', '1440/1024 layouts'] }, null, 2));
} finally {
  await browser.close();
}
